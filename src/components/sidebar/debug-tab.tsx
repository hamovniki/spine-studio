"use client";

import {
  Bone,
  Box,
  Grid3X3,
  Image as ImageIcon,
  RotateCcw,
  Spline,
} from "lucide-react";
import type { LucideIcon } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Switch } from "@/components/ui/switch";
import type { DebugOptions } from "@/lib/spine/types";
import { useViewerStore } from "@/store/viewer-store";

const DEBUG_ROWS: Array<{
  key: keyof DebugOptions;
  title: string;
  description: string;
  icon: LucideIcon;
}> = [
  {
    key: "bones",
    title: "Draw bones",
    description: "Bone origins and hierarchy",
    icon: Bone,
  },
  {
    key: "mesh",
    title: "Draw mesh",
    description: "Triangles and mesh hulls",
    icon: Grid3X3,
  },
  {
    key: "paths",
    title: "Draw paths",
    description: "Path constraint curves",
    icon: Spline,
  },
  {
    key: "boundingBoxes",
    title: "Bounding boxes",
    description: "Collision and hit shapes",
    icon: Box,
  },
  {
    key: "regions",
    title: "Region quads",
    description: "Raw attachment rectangles",
    icon: ImageIcon,
  },
];

export function DebugTab() {
  const debug = useViewerStore((state) => state.debug);
  const setDebug = useViewerStore((state) => state.setDebug);
  const resetDebug = useViewerStore((state) => state.resetDebug);
  const activeCount = Object.values(debug).filter(Boolean).length;

  return (
    <div className="space-y-3 p-3">
      <div className="flex items-start justify-between gap-2">
        <div>
          <h3 className="text-xs font-medium text-foreground">Debug overlays</h3>
          <p className="mt-1 text-[11px] leading-4 text-muted">
            Visual helpers are drawn on top of the current pose.
          </p>
        </div>
        <span className="rounded-md border border-border bg-panel px-1.5 py-0.5 font-mono text-[9px] text-muted">
          {activeCount} on
        </span>
      </div>

      <div className="overflow-hidden rounded-xl border border-border bg-panel/40">
        {DEBUG_ROWS.map(({ key, title, description, icon: Icon }, index) => (
          <div
            key={key}
            className={
              index > 0 ? "border-t border-border px-3 py-2.5" : "px-3 py-2.5"
            }
          >
            <div className="flex items-center gap-2.5">
              <span className="flex h-7 w-7 shrink-0 items-center justify-center rounded-md border border-border bg-surface-raised text-muted">
                <Icon className="h-3.5 w-3.5" />
              </span>
              <div className="min-w-0 flex-1">
                <p className="text-[11px] font-medium text-foreground">{title}</p>
                <p className="mt-0.5 text-[10px] leading-4 text-muted">
                  {description}
                </p>
              </div>
              <Switch
                label={title}
                checked={debug[key]}
                onCheckedChange={(checked) => setDebug(key, checked)}
              />
            </div>
          </div>
        ))}
      </div>

      <Button
        variant="ghost"
        size="sm"
        className="w-full"
        onClick={resetDebug}
        disabled={activeCount === 0}
      >
        <RotateCcw className="h-3.5 w-3.5" />
        Reset overlays
      </Button>

      <div className="rounded-xl border border-border bg-panel/45 px-3 py-2.5">
        <p className="font-mono text-[9px] uppercase tracking-[0.14em] text-muted">
          Renderer note
        </p>
        <p className="mt-1 text-[10px] leading-4 text-muted">
          Overlay primitives are generated by the runtime&apos;s debug renderer,
          so bone and mesh output matches the loaded skeleton exactly.
        </p>
      </div>
    </div>
  );
}
